// Netlify build step. server.js doesn't run on Netlify, so the parts of
// src/server/router.js that depend on data/apps.json are baked into the
// published web/ folder here instead:
//
// - data/apps.json is copied to web/apps.json, so /apps.json resolves the
//   way the router serves it locally.
// - web/_redirects gets one rewrite to app.html per in-development app,
//   mirroring the router's hasDevApp() gate. Any other unknown slug falls
//   through to web/404.html, which Netlify serves on its own.
//
// The fixed routes (/, /home, /app-store, ...) live in netlify.toml.
//
// Run with: bun src/build/netlify.js  (netlify.toml does this on deploy)

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const WEB_DIR = path.join(ROOT, "web");
const APPS_JSON = path.join(ROOT, "data", "apps.json");

// Same shape the router accepts for the generic app template.
const SLUG_PATTERN = /^[a-zA-Z0-9-]+$/;

// First path segments the router claims before it ever reaches the app
// template: redirects, pages, and the whitelisted static dirs.
const RESERVED_SLUGS = new Set(["app-store", "home", "style-guide", "privacy", "terms", "css", "js", "assets", "api"]);

// One `/slug /app.html 200` line per in-development app. Slugs that the
// router would route elsewhere first (reserved paths, or a custom site
// folder under web/) are left out so they keep their own page.
function devAppRedirects(devApps, customSiteSlugs) {
  return devApps
    .map((app) => app && app.slug)
    .filter((slug) => typeof slug === "string" && SLUG_PATTERN.test(slug))
    .filter((slug) => !RESERVED_SLUGS.has(slug) && !customSiteSlugs.includes(slug))
    .map((slug) => `/${slug}  /app.html  200`);
}

// Folders under web/ with their own index.html — the router's custom app
// sites (nine-tiles-puzzle, drinko, ...).
function findCustomSiteSlugs(webDir) {
  return fs
    .readdirSync(webDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(webDir, entry.name, "index.html")))
    .map((entry) => entry.name);
}

function build() {
  // Parsed here rather than through dev-apps.js's loadDevApps(), which
  // falls back to [] on a bad file — a deploy should fail loudly instead of
  // shipping with every in-development page missing.
  const devApps = JSON.parse(fs.readFileSync(APPS_JSON, "utf8"));
  if (!Array.isArray(devApps)) throw new Error("data/apps.json must be an array");

  fs.copyFileSync(APPS_JSON, path.join(WEB_DIR, "apps.json"));

  const lines = devAppRedirects(devApps, findCustomSiteSlugs(WEB_DIR));
  fs.writeFileSync(
    path.join(WEB_DIR, "_redirects"),
    ["# Generated by src/build/netlify.js — do not edit.", ...lines, ""].join("\n"),
  );
  console.log(`Wrote web/apps.json and ${lines.length} app redirect(s) to web/_redirects`);
}

if (require.main === module) build();

module.exports = { devAppRedirects, findCustomSiteSlugs };
